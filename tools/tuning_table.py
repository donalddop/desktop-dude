"""Build the README table of every key you can put in the "tuning" block of dude_config.json.

The table comes straight from tuning.py: field names and defaults from the Tuning dataclass, the explanation
from the comment behind each field and the "# ----" section comments above them.

    uv run python tools/tuning_table.py           # print the table
    uv run python tools/tuning_table.py --write   # put it in README.md between the tuning-table markers
    uv run python tools/tuning_table.py --check   # exit 1 if README.md is out of date (tests do this too)
"""

from __future__ import annotations

import ast
import io
import sys
import tokenize
from dataclasses import fields
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TUNING = ROOT / "tuning.py"
README = ROOT / "README.md"
START = "<!-- tuning-table:start (generated by tools/tuning_table.py --write, do not edit by hand) -->"
END = "<!-- tuning-table:end -->"


def _comments(source: str) -> dict[int, str]:
    """Line number -> comment text (without '#') for every comment in the source."""
    out = {}
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            out[tok.start[0]] = tok.string.lstrip("#").strip()
    return out


def rows(source: str | None = None) -> list[tuple[str, list[tuple[str, str]]]]:
    """[(section, [(key, comment), ...]), ...] in the order tuning.py lists them."""
    source = TUNING.read_text(encoding="utf-8") if source is None else source
    comments = _comments(source)
    cls = next(n for n in ast.walk(ast.parse(source)) if isinstance(n, ast.ClassDef) and n.name == "Tuning")
    sections: list[tuple[str, list[tuple[str, str]]]] = []
    prev_line = cls.lineno
    base = ""
    for node in cls.body:
        if not (isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)):
            continue
        for line in range(prev_line + 1, node.lineno):
            text = comments.get(line, "")
            if text.startswith("----"):
                sections.append((text.strip("- ").strip(), []))
        if not sections:
            sections.append(("", []))
        key = node.target.id
        text = comments.get(node.lineno, "")
        if text.startswith("..."):
            text = f"{text.removeprefix('...').removesuffix('...').strip()} (goes with `{base}`)"
        else:
            base = key
        sections[-1][1].append((key, text.removesuffix("...").strip()))
        prev_line = node.end_lineno or node.lineno
    return sections


def _num(v: float) -> str:
    return f"{v:g}"


def _fmt(value) -> str:
    if isinstance(value, dict):
        return ", ".join(f"{k} {_num(v)}" for k, v in value.items())
    if isinstance(value, tuple):
        return "[" + ", ".join(_num(v) for v in value) + "]"
    return _num(value)


def table() -> str:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from tuning import Tuning

    defaults = Tuning()
    out = []
    seen = set()
    for section, items in rows():
        if section:
            out.append(f"**{section[0].upper()}{section[1:]}**\n")
        out.append("| Key | Default | What it does |")
        out.append("| --- | --- | --- |")
        for key, text in items:
            seen.add(key)
            out.append(f"| `{key}` | {_fmt(getattr(defaults, key))} | {text.replace('|', '/')} |")
        out.append("")
    missing = {f.name for f in fields(Tuning)} - seen
    if missing:
        raise SystemExit(f"tuning_table: fields not found in tuning.py source: {sorted(missing)}")
    return "\n".join(out).rstrip() + "\n"


def render_readme(readme: str, tbl: str) -> str:
    """README text with the block between the markers replaced by `tbl`."""
    if START not in readme or END not in readme:
        raise SystemExit("tuning_table: README.md has no tuning-table markers")
    head, rest = readme.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{tbl}\n{END}{tail}"


def main(argv: list[str]) -> int:
    tbl = table()
    if "--write" in argv or "--check" in argv:
        current = README.read_text(encoding="utf-8")
        wanted = render_readme(current, tbl)
        if "--check" in argv:
            if current != wanted:
                print("README.md tuning table is out of date: uv run python tools/tuning_table.py --write")
                return 1
            print("README.md tuning table is up to date")
            return 0
        README.write_text(wanted, encoding="utf-8", newline="")
        print("README.md tuning table written")
        return 0
    print(tbl, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
